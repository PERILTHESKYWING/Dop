// Writes hub/lib/skills-seed.js from ../.claude/account-skills/*/SKILL.md.
// The hub runs from the hub/ folder alone on Vercel, so the skills are baked
// into a module instead of read from the repo. Run: node hub/seed-skills.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '.claude', 'account-skills');
const skills = {};
for (const d of readdirSync(src, { withFileTypes: true })) {
  if (!d.isDirectory()) continue;
  skills[d.name] = readFileSync(join(src, d.name, 'SKILL.md'), 'utf8');
}
writeFileSync(join(here, 'lib', 'skills-seed.js'), `// Generated by hub/seed-skills.mjs from .claude/account-skills. Do not edit.\nexport const SEED_SKILLS = ${JSON.stringify(skills, null, 1)};\n`);
console.log(`Seeded ${Object.keys(skills).length} skills`);
